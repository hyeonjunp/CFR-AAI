"""
AbLang-based Antibody-Antigen Interaction Prediction Model
— frozen CDR-aware antibody encoder,
  shared antibody Linear-ReLU-MaskedBatchNorm projection,
  configurable multi-head interaction maps and cross-context aggregation.

Antibody encoder: AbLang (ESM2 아님)
--------------------------------------
항체는 AbLang heavy/light 전용 백본으로, 항원은 ESM2 로 인코딩한다 (AbLang 의
vocab/위치임베딩은 항체 V 도메인 전용이라 항원 서열을 담지 못한다). 항체(768)와
항원(640)은 입력 차원이 달라 ProjectionBlock 을 따로 두지만, VH/VL 은 같은
attn_block(frozen)을 통과해 같은 표현 공간에 있으므로 ab_proj 하나를 공유한다.

Architecture
------------
VH
  -> frozen AbLang heavy hidden state -> frozen AbLangStyleLayer (attn_block)
  -> shared Ab projection 768 -> 256 (Linear -> ReLU -> MaskedBatchNorm)
  -> P_vh

VL
  -> frozen AbLang light hidden state -> frozen AbLangStyleLayer (attn_block)
  -> SAME shared Ab projection 768 -> 256 (Linear -> ReLU -> MaskedBatchNorm)
  -> P_vl

Antibody
  P_ab = [P_vh || P_vl]                       # sequence-axis concat

Antigen
  -> frozen ESM2 hidden state (640)
  -> Ag projection 640 -> 256 (Linear -> ReLU -> MaskedBatchNorm)
  -> P_ag

The residue-pair interaction map is generated by the low-rank BANLayer.

No residual update is used:
  P_ag + C_ag   X
  P_ab + C_ab   X

Pooling
  p_ab = masked_mean(C_ab)                    # VH/VL concatenated first
  p_ag = masked_mean(C_ag)

Prediction
  [p_ab || p_ag]
  -> compact MLP -> binding logit

No IIP.
No CNN/top-k pooling.
No separate VH/VL projection.
No Q/K/V dot-product interaction map.

같은 폴더의 참고 파일 (여기서 import 하지 않는다):
"""

from typing import Dict, Optional

import torch
from torch import Tensor, nn


from ban import BANLayer


# ============================================================================
# Mask helpers
# ============================================================================

def special_token_mask(attn_mask: Tensor) -> Tensor:
    """True at the start/end token.

    ESM 은 <cls>/<eos>, AbLang 은 '<'/'>' 로 글자만 다르고 토큰 배치는 같다
    (pos 0 = 시작, 1..L = AA, L+1 = 끝, 이후 pad).
    """
    B, T = attn_mask.shape
    idx = torch.arange(T, device=attn_mask.device).unsqueeze(0).expand(B, T)
    eos_pos = attn_mask.sum(dim=1, keepdim=True) - 1
    return (idx == 0) | (idx == eos_pos)


def exclude_mask(attn_mask: Tensor) -> Tensor:
    """True = PAD or <cls>/<eos>."""
    return (attn_mask == 0) | special_token_mask(attn_mask)


def masked_mean_pool(x: Tensor, exclude: Tensor) -> Tensor:
    """Mean-pool valid residues only."""
    if x.shape[:2] != exclude.shape:
        raise ValueError(
            f"x[:2] and exclude must match, got {tuple(x.shape[:2])} "
            f"vs {tuple(exclude.shape)}"
        )

    valid = (~exclude.bool()).unsqueeze(-1).to(x.dtype)
    denom = valid.sum(dim=1)
    pooled = (x * valid).sum(dim=1) / denom.clamp_min(1.0)
    return torch.where(denom > 0, pooled, torch.zeros_like(pooled))


# ============================================================================
# 항체 768 / 항원 640 -> 256 projection: Linear -> ReLU -> MaskedBatchNorm
# ============================================================================

class MaskedBatchNorm1d(nn.Module):
    """
    BatchNorm for (B, T, C) sequence features using ONLY valid residues
    when computing batch statistics.

    valid_mask: (B, T), True = real amino-acid residue.
    PAD/<cls>/<eos> therefore do not affect mean/variance.
    """

    def __init__(
        self,
        num_features: int,
        eps: float = 1e-5,
        momentum: float = 0.1,
    ):
        super().__init__()
        self.eps = eps
        self.momentum = momentum

        self.weight = nn.Parameter(torch.ones(num_features))
        self.bias = nn.Parameter(torch.zeros(num_features))

        self.register_buffer("running_mean", torch.zeros(num_features))
        self.register_buffer("running_var", torch.ones(num_features))
        self.register_buffer("num_batches_tracked", torch.tensor(0, dtype=torch.long))

    def forward(self, x: Tensor, valid_mask: Tensor) -> Tensor:
        # Keep normalization statistics in fp32 under autocast.
        input_dtype = x.dtype
        x32 = x.float()
        valid = valid_mask.bool()

        if self.training and valid.any():
            m = valid.unsqueeze(-1).to(x32.dtype)
            n = m.sum()

            mean = (x32 * m).sum(dim=(0, 1)) / n
            var = (((x32 - mean) ** 2) * m).sum(dim=(0, 1)) / n

            with torch.no_grad():
                unbiased = var * n / (n - 1.0).clamp(min=1.0)
                self.running_mean.mul_(1.0 - self.momentum).add_(
                    self.momentum * mean.detach()
                )
                self.running_var.mul_(1.0 - self.momentum).add_(
                    self.momentum * unbiased.detach()
                )
                self.num_batches_tracked += 1
        else:
            # Eval mode, or an all-empty stream: use stored running statistics.
            mean = self.running_mean
            var = self.running_var

        y = (x32 - mean) * torch.rsqrt(var + self.eps)
        y = y * self.weight + self.bias
        return y.to(input_dtype)


class ProjectionBlock(nn.Module):
    """Position-wise Linear -> ReLU -> MaskedBatchNorm; no token mixing."""

    def __init__(self, in_dim: int, out_dim: int):
        super().__init__()
        self.fc = nn.Linear(in_dim, out_dim)
        self.act = nn.ReLU()
        self.bn = MaskedBatchNorm1d(out_dim)

        nn.init.xavier_uniform_(self.fc.weight)
        nn.init.constant_(self.fc.bias, 0.0)

    def forward(self, x: Tensor, exclude: Tensor) -> Tensor:
        valid = ~exclude.bool()
        x = self.act(self.fc(x))
        x = self.bn(x, valid)
        return x


# ============================================================================
# Main model
# ============================================================================

class AbLangAbAgModel(nn.Module):
    """
    Frozen CDR-aware AbLang antibody encoder + shared Ab projection + Ag projection +
    configurable multi-head interaction + bidirectional cross-context.

    Parameters
    ----------
    ag_embed_dim      : 항원 ESM2 hidden size (esm2_t30_150M=640; esm2_t33_650M=1280 도 가능).
                        ag_proj 의 입력 차원이다.
    co_attn_heads          : BAN interaction-map glimpse 수 (V6 기본 1).
    """

    ABLANG_LAYER_NORM_EPS = 1e-12   # ABlang hparams.layer_norm_eps (heavy/light 동일)

    def __init__(
        self,
        ag_embed_dim: int = 640,
        num_classes: int = 1,
        dropout: float = 0.1,
        co_attn_heads: int = 1,
        ban_k: int = 3,
        ban_act: str = "ReLU",
        ban_dropout: float = 0.2,
        use_vl: bool = True,
        proj_dim: int = 256,
        use_interaction_residual: bool = True,
        use_ban_pooling: bool = True,
        ban_pool_dim: int = 256,
        ban_softmax: bool = False,
        classification_hidden: int = 256,
        classification_out: int = 128,
        use_ban_logit_gate: bool = False,
        detach_ban_gate: bool = False,
    ):
        super().__init__()

        self.use_vl = use_vl
        self.proj_dim = proj_dim
        self.co_attn_heads = co_attn_heads
        self.use_interaction_residual = use_interaction_residual
        self.use_ban_pooling = use_ban_pooling
        self.ban_softmax = ban_softmax
        self.use_ban_logit_gate = use_ban_logit_gate
        self.detach_ban_gate = detach_ban_gate

        # build_embeddings.py stores the post-CDR residue representation.
        ab_dim = 768
        print("[AbLang] using cached post-CDR residue embeddings")

        # ------------------------------------------------------------------
        # Shared antibody projection: Linear -> ReLU -> MaskedBatchNorm.
        # SAME parameters are used for VH and VL. 항원은 인코더(ESM2)와 입력
        # 차원(640)이 달라 별도 ag_proj 를 둔다.
        # ------------------------------------------------------------------
        self.ab_proj = ProjectionBlock(ab_dim, proj_dim)
        self.ag_proj = ProjectionBlock(ag_embed_dim, proj_dim)

        # ------------------------------------------------------------------
        # The referenced low-rank BANLayer creates the residue-pair map.
        # ``co_attn_heads`` is the number of BAN glimpses (V6 default: one).
        # ------------------------------------------------------------------
        self.ban = BANLayer(proj_dim, proj_dim, h_dim=ban_pool_dim,
                            h_out=co_attn_heads, act=ban_act,
                            dropout=ban_dropout, k=ban_k)
        if use_interaction_residual:
            # Start near the prior context-only baseline, then learn how much
            # sequence-local information to retain.
            self.ag_residual_gate = nn.Parameter(torch.tensor(-2.0))
            self.ab_residual_gate = nn.Parameter(torch.tensor(-2.0))
        self.ban_glimpse_fusion = nn.ModuleList([
            nn.Sequential(nn.Linear(ban_pool_dim, ban_pool_dim), nn.GELU())
            for _ in range(co_attn_heads)
        ]) if use_ban_pooling else None

        # Global embedding evidence and sparse pair-map evidence predict
        # separately, then combine only their logits.
        # V5: concatenate VH/VL residues before one masked mean pool, so
        # each valid antibody residue receives equal weight.
        embedding_in_dim = proj_dim * 2
        self.embedding_classifier = nn.Sequential(
            nn.Linear(embedding_in_dim, classification_hidden),
            nn.BatchNorm1d(classification_hidden),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(classification_hidden, classification_hidden),
            nn.BatchNorm1d(classification_hidden),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(classification_hidden, classification_out),
            nn.BatchNorm1d(classification_out),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(classification_out, num_classes),
        )
        self.map_classifier = nn.Sequential(
            nn.Linear(ban_pool_dim, classification_out),
            nn.BatchNorm1d(classification_out),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(classification_out, num_classes),
        ) if use_ban_pooling else None

        trainable = sum(p.numel() for p in self.parameters() if p.requires_grad)
        total = sum(p.numel() for p in self.parameters())
        print(f"[AbLangAbAgModel] Trainable: {trainable:,} / {total:,}")

    def _fuse_ban_glimpses(self, glimpse_features: Tensor) -> Tensor:
        """Residual multi-glimpse fusion; no mean reduction across maps."""
        fused = torch.zeros_like(glimpse_features[:, 0])
        for h, layer in enumerate(self.ban_glimpse_fusion):
            fused = fused + layer(glimpse_features[:, h])
        return fused

    # ----------------------------------------------------------------------
    # Forward
    # ----------------------------------------------------------------------
    def forward(
        self,
        vh_hidden: Tensor,
        vh_attn_mask: Tensor,
        vl_hidden: Optional[Tensor],
        vl_attn_mask: Optional[Tensor],
        ag_emb: Tensor,
        ag_attn_mask: Tensor,
        return_attn: bool = False,
        return_branch_logits: bool = False,
    ):
        # ================================================================
        # 1. Frozen antibody representations + masks
        # ================================================================
        vh_base, vh_pad = vh_hidden, exclude_mask(vh_attn_mask)
        if self.use_vl:
            if vl_hidden is None or vl_attn_mask is None:
                raise ValueError("vl_hidden and vl_attn_mask are required when use_vl=True")
            vl_base, vl_pad = vl_hidden, exclude_mask(vl_attn_mask)
        else:
            vl_base = vl_pad = None
        ag_pad = exclude_mask(ag_attn_mask)

        # ================================================================
        # 2. Linear -> ReLU -> MaskedBatchNorm projection
        #    Shared Ab projection / separate Ag projection
        # ================================================================
        p_ag = self.ag_proj(ag_emb, ag_pad)
        p_ag = p_ag.masked_fill(ag_pad.unsqueeze(-1), 0.0)

        vh_len = vh_base.size(1)

        if self.use_vl:
            # VH와 VL을 먼저 sequence axis로 결합
            ab_base = torch.cat([vh_base, vl_base], dim=1)
            ab_pad = torch.cat([vh_pad, vl_pad], dim=1)

            # Shared Linear/ReLU/MaskedBatchNorm을 한 번만 적용
            p_ab = self.ab_proj(ab_base, ab_pad)
            p_ab = p_ab.masked_fill(ab_pad.unsqueeze(-1), 0.0)

            # 다시 VH/VL로 분리
            p_vh = p_ab[:, :vh_len, :]
            p_vl = p_ab[:, vh_len:, :]

        else:
            p_vh = self.ab_proj(vh_base, vh_pad)
            p_vh = p_vh.masked_fill(vh_pad.unsqueeze(-1), 0.0)

            p_vl = None
            p_ab = p_vh
            ab_pad = vh_pad

        # ================================================================
        # 3. BAN attention map -> bidirectional cross-context
        #
        # BAN produces residue-pair maps A (antigen x antibody).  The map is
        # normalized over valid residue pairs and used directly to aggregate
        # the opposite sequence.  There is deliberately no IIP branch here.
        # ================================================================
        raw_maps, ag_ban, ab_ban = self.ban(p_ag, p_ab, return_features=True)
        pair_valid = ((~ag_pad.bool()).unsqueeze(1).unsqueeze(-1)
                      & (~ab_pad.bool()).unsqueeze(1).unsqueeze(-2))
        if self.ban_softmax:
            flat = raw_maps.float().masked_fill(~pair_valid, torch.finfo(torch.float32).min)
            base_head_maps = torch.softmax(flat.flatten(2), dim=-1).view_as(raw_maps)
        else:
            base_head_maps = raw_maps
        base_head_maps = base_head_maps.masked_fill(~pair_valid, 0.0)

        # Direct BAN prediction from the same map (original low-rank bilinear
        # pooling), followed by the requested soft map update.
        if self.use_ban_pooling:
            map_feature = self._fuse_ban_glimpses(
                self.ban.bilinear_pool(base_head_maps, ag_ban, ab_ban)
            )
            map_logits = self.map_classifier(map_feature)
            if self.use_ban_logit_gate:
                gate_logits = map_logits.detach() if self.detach_ban_gate else map_logits
                interaction_gate = torch.sigmoid(gate_logits).view(-1, 1, 1, 1)
            else:
                interaction_gate = torch.ones_like(base_head_maps[:, :1, :1, :1])
        else:
            map_logits = map_feature = interaction_gate = None
            interaction_gate = torch.ones_like(base_head_maps[:, :1, :1, :1])

        head_maps = base_head_maps * interaction_gate
        interaction_map = head_maps.mean(dim=1)
        # Same attention map in both directions; no IIP/pseudo-pooling branch.
        c_ag = torch.bmm(interaction_map, p_ab).masked_fill(ag_pad.unsqueeze(-1), 0.0)
        c_ab = torch.bmm(interaction_map.transpose(1, 2), p_ag).masked_fill(ab_pad.unsqueeze(-1), 0.0)
        ag_map = ab_map = interaction_map
        ag_head_maps = ab_head_maps = head_maps

        if self.use_interaction_residual:
            c_ag = p_ag + torch.sigmoid(self.ag_residual_gate) * c_ag
            c_ab = p_ab + torch.sigmoid(self.ab_residual_gate) * c_ab
            c_ag = c_ag.masked_fill(ag_pad.unsqueeze(-1), 0.0)
            c_ab = c_ab.masked_fill(ab_pad.unsqueeze(-1), 0.0)

        # ================================================================
        # 4. Split antibody context back into VH / VL (for inspection only)
        # ================================================================
        c_vh = c_ab[:, :vh_len, :]
        if self.use_vl:
            c_vl = c_ab[:, vh_len:, :]
        else:
            c_vl = None

        # ================================================================
        # 5. Masked mean pooling of INTERACTION-CONDITIONED context only.
        #    V5: VH/VL are already concatenated in c_ab, so pool once.
        # ================================================================
        pooled_ab = masked_mean_pool(c_ab, ab_pad)
        pooled_ag = masked_mean_pool(c_ag, ag_pad)
        embedding_vec = torch.cat([pooled_ab, pooled_ag], dim=-1)

        # ================================================================
        # 6. Binding prediction
        # ================================================================
        embedding_logits = self.embedding_classifier(embedding_vec)
        logits = embedding_logits if map_logits is None else 0.5 * (embedding_logits + map_logits)

        if return_attn:
            interaction_info: Dict[str, object] = {
                # Final map used for BOTH directions.
                "interaction_map": interaction_map,
                # Individual per-head sigmoid maps.
                "head_maps": head_maps,
                "ag_map": ag_map,
                "ab_map": ab_map,
                "ag_head_maps": ag_head_maps,
                "ab_head_maps": ab_head_maps,
                "base_head_maps": base_head_maps,
                "interaction_gate": interaction_gate,
                # Projected states.
                "p_vh": p_vh,
                "p_vl": p_vl,
                "p_ab": p_ab,
                "p_ag": p_ag,
                # Interaction-conditioned contexts.
                "c_vh": c_vh,
                "c_vl": c_vl,
                "c_ab": c_ab,
                "c_ag": c_ag,
                # Pooled representations.
                "ab_pooled": pooled_ab,
                "ag_pooled": pooled_ag,
                "ban_map_feature": map_feature if self.use_ban_pooling else None,
                # Prediction made by the original BAN bilinear pooling path.
                "ban_logits": map_logits,
                "map_logits": map_logits,
            }
            return logits, interaction_info
        if return_branch_logits:
            return logits, embedding_logits, map_logits
        return logits
